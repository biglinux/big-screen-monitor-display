#!/usr/bin/env python3
"""Generate the AUR package (pkgbuild/aur/) from pkgbuild/PKGBUILD.

The AUR package is "big-screen-monitor-display-git": same dependencies, same
package() and the same install script as the BigLinux package, but built from
the development repository with a version taken from git (v5.5.2.r3.gabc1234).

    tools/make_aur.py            rewrite pkgbuild/aur/PKGBUILD and pkgbuild.install
    tools/make_aur.py --check    exit 1 when they are out of date (tests do this)

Publishing (needs an AUR account and its SSH key):
    git clone ssh://aur@aur.archlinux.org/big-screen-monitor-display-git.git aur-repo
    cp pkgbuild/aur/* aur-repo/ && cd aur-repo && makepkg --printsrcinfo > .SRCINFO
    git add -A && git commit -m "Update" && git push
"""

import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
SRC = os.path.join(ROOT, "pkgbuild", "PKGBUILD")
INSTALL = os.path.join(ROOT, "pkgbuild", "pkgbuild.install")
OUT_DIR = os.path.join(ROOT, "pkgbuild", "aur")
NAME = "big-screen-monitor-display"
REPO = "https://github.com/ruscher/big-screen-monitor-display"

HEADER = f"""# Maintainer: Rafael Ruscher (BigLinux)
# Generated by tools/make_aur.py from pkgbuild/PKGBUILD - do not edit by hand.
_pkgname={NAME}
pkgname={NAME}-git
"""

VERSION = """pkgver=5.5.2
pkgrel=1
pkgver() {
    cd "${srcdir}/${_pkgname}"
    git describe --long --tags --abbrev=7 --match 'v*' | sed 's/^v//;s/\\([^-]*-g\\)/r\\1/;s/-/./g'
}
"""


def render():
    with open(SRC, encoding="utf-8") as fh:
        text = fh.read()
    text = text.replace(f"pkgname={NAME}\n", HEADER, 1)
    text = re.sub(r"pkgver=\$\(date[^\n]*\)\npkgrel=\$\(date[^\n]*\)\n", lambda _m: VERSION, text, count=1)
    text = re.sub(r'url="[^"]*"', f'url="{REPO}"', text, count=1)
    text = re.sub(r'provides=\("\$pkgname"\)', f'provides=("{NAME}")\nconflicts=("{NAME}")', text, count=1)
    text = re.sub(r'source=\("[^"]*"\)', f'source=("{NAME}::git+{REPO}.git")', text, count=1)
    # BigLinux's build service checks the template marker; the AUR has no use for the CI branch.
    body_start = text.index("package() {")
    head, body = text[:body_start], text[body_start:]
    body = body.replace("${pkgname}", "${_pkgname}").replace("$pkgname", "$_pkgname")
    head = head.replace('if [ -e "pkgbuild.install" ];then\n    install=pkgbuild.install\nfi\n',
                        "install=pkgbuild.install\n")
    return head + body


def outputs():
    with open(INSTALL, encoding="utf-8") as fh:
        install = fh.read()
    return {os.path.join(OUT_DIR, "PKGBUILD"): render(), os.path.join(OUT_DIR, "pkgbuild.install"): install}


def main(argv):
    files = outputs()
    if "--check" in argv:
        stale = [path for path, text in files.items()
                 if not os.path.exists(path) or open(path, encoding="utf-8").read() != text]
        if stale:
            print("pkgbuild/aur desatualizado: rode tools/make_aur.py", file=sys.stderr)
            return 1
        return 0
    os.makedirs(OUT_DIR, exist_ok=True)
    for path, text in files.items():
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(path)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
